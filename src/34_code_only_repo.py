# -*- coding: utf-8 -*-
"""Point the report and the deck at a source-code-only repository.

The public repository keeps the numbered scripts, requirements.txt and the
README; curated data, result tables, figures, the report and the slides are not
committed there. Two places in the deliverables claimed otherwise:

  * Appendix A's "Version-control location" line (report)
  * the closing credit line of the last slide (deck)

Both are reworded here, the link itself is left untouched, and the report and
deck PDFs are re-exported.

Usage:
    python src/34_code_only_repo.py --check
    python src/34_code_only_repo.py            # edit + export both PDFs
    python src/34_code_only_repo.py --no-pdf
"""
from __future__ import annotations

import argparse
import importlib.util
import shutil
import tempfile
from copy import deepcopy
from pathlib import Path

from docx import Document
from docx.oxml.ns import qn
from pptx import Presentation

ROOT = Path(__file__).resolve().parents[1]
DOCX = ROOT / "report" / "AIDD8122_Final_Report_HuangYong_P2600222_v2.docx"
PPTX = (ROOT / "AIDD8122_Final_Presentation_HuangYong"
        / "AIDD8122_Final_Presentation_HuangYong_10min.pptx")

NEW_PARA = ("The repository is deliberately limited to source code: it carries the numbered "
            "scripts, requirements.txt and a README with the run order. Curated data, result "
            "tables, figures, this report and the slides are not committed there; they are "
            "regenerated by the scripts or supplied in the submission package described above.")

OLD_DECK_LINE = ("decision rule — not a single predicted number. Code, curated data and "
                 "filter logs are in the repository.")
NEW_DECK_LINE = ("decision rule — not a single predicted number. The repository holds the "
                 "source code only.")


def paragraph_after(anchor):
    """A body paragraph with the same pPr/rPr as the paragraph before the anchor."""
    return anchor._p.getprevious()


def insert_repo_note(doc) -> bool:
    anchor = None
    for p in doc.paragraphs:
        if p.text.strip().startswith("Version-control location:"):
            anchor = p
            break
    assert anchor is not None, "version-control paragraph not found"

    nxt = anchor._p.getnext()
    if nxt is not None and NEW_PARA[:40] in "".join(nxt.itertext()):
        return False                                   # idempotent

    template = paragraph_after(anchor)
    new_p = deepcopy(template)

    for child in list(new_p):
        if child.tag != qn("w:pPr"):
            new_p.remove(child)

    src_run = template.findall(qn("w:r"))[0]
    run = deepcopy(src_run)
    for node in list(run):
        if node.tag in (qn("w:t"), qn("w:br"), qn("w:tab")):
            run.remove(node)
    text = run.makeelement(qn("w:t"), {})
    text.set(qn("xml:space"), "preserve")
    text.text = NEW_PARA
    run.append(text)
    new_p.append(run)

    anchor._p.addnext(new_p)
    return True


def reword_deck(prs) -> bool:
    slide = prs.slides[-1]
    for shape in slide.shapes:
        if not shape.has_text_frame:
            continue
        for para in shape.text_frame.paragraphs:
            if OLD_DECK_LINE in para.text:
                runs = para.runs
                assert runs, "credit paragraph has no runs"
                runs[0].text = para.text.replace(OLD_DECK_LINE, NEW_DECK_LINE)
                for extra in runs[1:]:
                    extra._r.getparent().remove(extra._r)
                return True
    return False


def export_report_pdf() -> None:
    spec = importlib.util.spec_from_file_location(
        "c27", Path(__file__).with_name("27_condense_report.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.export_pdf()


def export_deck_pdf() -> None:
    import win32com.client as win32

    pdf = PPTX.with_suffix(".pdf")
    tmp = Path(tempfile.gettempdir()) / "aidd_deck_codeonly.pdf"
    app = win32.DispatchEx("PowerPoint.Application")
    try:
        pres = app.Presentations.Open(str(PPTX), WithWindow=False)
        pres.SaveCopyAs(str(tmp), 32)
        pres.Close()
    finally:
        app.Quit()
    shutil.copy2(tmp, pdf)
    print(f"  deck PDF       : {pdf.name}  ({pdf.stat().st_size:,} bytes)")


def check() -> None:
    doc = Document(str(DOCX))
    joined = "\n".join(p.text for p in doc.paragraphs)
    assert NEW_PARA[:60] in joined, "report note missing"
    assert "Version-control location:" in joined
    prs = Presentation(str(PPTX))
    last = "\n".join(sh.text_frame.text for sh in prs.slides[-1].shapes if sh.has_text_frame)
    assert "source code only" in last and "curated data" not in last.lower()
    print("  check          : report note present, deck credit line updated")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--no-pdf", action="store_true")
    args = ap.parse_args()

    if args.check:
        check()
        return

    doc = Document(str(DOCX))
    report_changed = insert_repo_note(doc)
    if report_changed:
        doc.save(str(DOCX))
    print(f"  report note    : {'inserted' if report_changed else 'already present'}")

    prs = Presentation(str(PPTX))
    deck_changed = reword_deck(prs)
    if deck_changed:
        prs.save(str(PPTX))
    print(f"  deck credit    : {'reworded' if deck_changed else 'already reworded'}")

    if not args.no_pdf:
        if report_changed:
            export_report_pdf()
        if deck_changed:
            export_deck_pdf()
    check()


if __name__ == "__main__":
    main()
